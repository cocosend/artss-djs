'use strict';
const {readFileSync}=require('node:fs');
const {createHash}=require('node:crypto');
const assert=require('node:assert/strict');
const source=readFileSync('studio.js','utf8');
const start=source.indexOf('function makePCM(');
const end=source.indexOf('function createBuffer(',start);
assert(start>=0&&end>start,'approved synthesizer implementation missing');
const fingerprint=createHash('sha256').update(source.slice(start,end)).digest('hex');
const expected='87260389afeeb6ed5d7003bb5ee52aae80415b647e9e019b99560145c46db5be';
assert.equal(fingerprint,expected,'approved ARTSS STUDIO v8 sound signature changed; review synth modifications explicitly');
const names=(source.match(/const PAD_NAMES=/)||[]).length;
assert.equal(names,1,'only one instrument bank declaration expected');
console.log('PASS unchanged approved 8.0 audio synthesis SHA256: '+fingerprint.slice(0,16));